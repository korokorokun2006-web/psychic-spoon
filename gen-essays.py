def dump(name, data):
    p = OUT / name
    p.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {p} n={len(data)} chars_avg={sum(len(json.dumps(x,ensure_ascii=False)) for x in data)//max(1,len(data))}")


def pad(text: str, target: int, extra_blocks: list[str]) -> str:
    i = 0
    filler = (
        "本事例の固有名詞・数値・組織名は学習用に創作したものである。"
        "解答では本文の事実（制約、数値、関係者の主張、現行システムの弱点）を引用し、"
        "一般論だけで終わらせないこと。設計案には主キー、外部キー、障害時の切戻し、"
        "検証方法、残存リスク、役割分担を含める。"
    )
    while len(text) < target:
        if extra_blocks:
            text += "\n\n" + extra_blocks[i % len(extra_blocks)]
        text += f"\n\n【補遺{i + 1}】{filler} 連番{i + 1}の確認観点: 追跡可能性、再現手順、測定指標。"
        i += 1
        if i > 60:
            break
    return text


def blank(bid, label, prompt, choices, answer, explanation):
    return {
        "id": bid, "label": label, "prompt": prompt,
        "choices": choices, "answer": answer, "explanation": explanation,
    }


def part(pid, label, prompt, typ, answer, max_points, rubric, explanation, choices=None):
    d = {
        "id": pid, "label": label, "prompt": prompt, "type": typ,
        "answer": answer, "maxPoints": max_points, "rubric": rubric, "explanation": explanation,
    }
    if choices:
        d["choices"] = choices
    return d


