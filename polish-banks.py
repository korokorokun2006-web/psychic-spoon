def main():
    sec = {q["id"]: q for q in build_security()}
    fe_path = ROOT / "fe-b.json"
    fe = json.loads(fe_path.read_text())
    replaced = 0
    for i, q in enumerate(fe):
        if q["id"] in sec:
            fe[i] = sec[q["id"]]
            replaced += 1
        else:
            polish_multi_expl(q)
    assert replaced == 20, replaced
    fe_path.write_text(json.dumps(fe, ensure_ascii=False, separators=(",", ":")))

    for name in ("ip.json", "fe-a.json", "ap-a.json", "db-a.json"):
        path = ROOT / name
        data = json.loads(path.read_text())
        for q in data:
            polish_mcq(q)
        path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
        print(name, len(data), "mcq cleaned")

    ap_path = ROOT / "ap-b.json"
    ap = json.loads(ap_path.read_text())
    for q in ap:
        q["parts"] = ap_parts(q["category"])
        q["passage"] = clean_text_keep_newlines(q["passage"])
    ap_path.write_text(json.dumps(ap, ensure_ascii=False, separators=(",", ":")))
    print("ap-b", len(ap))

    db_path = ROOT / "db-b.json"
    db = json.loads(db_path.read_text())
    for q in db:
        for p in q["parts"]:
            p["explanation"] = clean_text(p.get("explanation", "")) or p.get("explanation", "")
            if p.get("answer") and p["answer"] not in p["explanation"]:
                p["explanation"] = (p["explanation"] + " 模範解答：" + p["answer"]).strip()
    db_path.write_text(json.dumps(db, ensure_ascii=False, separators=(",", ":")))
    print("db-b", len(db))

    # lengths
    lens = [len(q["passage"]) for q in sec.values()]
    print("security passages", min(lens), max(lens), "unique", len({q["passage"] for q in sec.values()}))
    # uniqueness within year
    from collections import Counter

    c = Counter(q["passage"] for q in sec.values())
    print("dup passages", sum(1 for v in c.values() if v > 1))


def clean_text_keep_newlines(text: str) -> str:
    lines = []
    for line in text.splitlines():
        lines.append(clean_text(line) if line.strip() else "")
    return "\n".join(lines).strip()


if __name__ == "__main__":
    main()
