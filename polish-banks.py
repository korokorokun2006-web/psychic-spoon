def clean_text(text: str) -> str:
    s = text or ""
    s = s.replace("题", "題")
    for pat in BOILER:
        s = re.sub(pat, "", s)
    s = re.sub(
        r"「[^」]+」(?:、「[^」]+」)*\s*は、それぞれ別の枠組みや用語であり本題の定義には当たりません。?",
        "",
        s,
    )
    s = re.sub(r"誤りの選択肢は定義・目的・対象が異なります。?", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def polish_mcq(q):
    expl = clean_text(q.get("explanation", ""))
    ans = q["choices"][q["answer"]]
    mark = "アいうエ"[q["answer"]] if False else "アイウエ"[q["answer"]]
    tail = f"したがって正解は{mark}「{ans}」である。"
    if ans not in expl and tail not in expl:
        expl = (expl + " " + tail).strip()
    wrong = [c for i, c in enumerate(q["choices"]) if i != q["answer"]]
    if not any(w in expl for w in wrong) and "他の選択肢は、定義・計算結果" not in expl:
        expl += " 他の選択肢は、定義・計算結果・適用場面のいずれかが本文の条件と異なる。"
    q["explanation"] = expl
    return q


