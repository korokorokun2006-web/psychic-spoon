def choice(i, prompt, choices, answer_index, explanation):
    mark = "アイウエ"[answer_index]
    return {
        "id": i,
        "label": f"設問{i}",
        "prompt": prompt,
        "type": "choice",
        "choices": choices,
        "answer": mark,
        "maxPoints": 10,
        "rubric": choices[answer_index],
        "explanation": explanation + f" 正解は{mark}。",
    }


def fill(i, prompt, answer, rubric, explanation):
    return {
        "id": i,
        "label": f"設問{i}",
        "prompt": prompt,
        "type": "fill",
        "answer": answer,
        "maxPoints": 10,
        "rubric": rubric,
        "explanation": explanation + f" 期待する語句は「{answer}」。",
    }


def essay(i, prompt, answer, rubric):
    return {
        "id": i,
        "label": f"設問{i}",
        "prompt": prompt,
        "type": "essay",
        "answer": answer,
        "maxPoints": 15,
        "rubric": rubric,
        "explanation": "採点は次の要点を含むかで見る。" + answer,
    }


