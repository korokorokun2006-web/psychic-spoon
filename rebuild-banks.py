def expand_fe_b() -> list[dict]:
    # unique 16 pseudo per year from r8 list, rewritten traces for other years
    extras_by_year = {
        "r7": "添字は 1 から。配列は空でない。",
        "r6": "整数除算は 0 方向（または言語の ÷ に準ずる）とする。",
        "r5": "比較は安定で、同じ値なら添字の小さい方を優先する。",
        "r4": "オーバーフローは考えない。n は 1 以上。",
        "r8": "配列の添字は 1 からとする。",
    }
    # For years other than r8, mutate traces and titles using year index
    out = []
    base = PSEUDO["r8"]
    for yi, year in enumerate(FE_YEARS):
        n = 1
        for item in base:
            cat, title, code, stem, blanks = item
            # uniquify title/traces per year
            title2 = title if yi == 0 else f"{title}（{['','改訂','応用入力','境界値','別トレース'][yi]}）"
            code2 = code
            if yi == 1:
                code2 = code.replace("i ← 1", "i ← 1  /* 先頭 */")
            bl = []
            for b in blanks:
                bid, lab, pr, ch, ans, ex = b
                ch2, a2 = rot(list(ch), ans, yi)
                # tweak numeric traces
                pr2 = pr
                if year == "r7" and "n=3" in pr:
                    pr2 = pr.replace("n=3, a=(2,5,1)", "n=4, a=(3,3,3,1)").replace("8", "?")
                    if "戻り値" in pr2 and cat.startswith("擬似言語（基礎）") and "累積" in title:
                        ch2 = ["10", "9", "4", "3"]
                        a2 = 0
                        ex = "3+3+3+1=10。件数4や最大3と混同しないこと。"
                bl.append(blank(bid, lab, pr2, ch2, a2, ex + " プログラムの初期化・条件・更新を順に追跡して一意に決まります。"))
            out.append(multi(
                "fe", year, n, cat, title2, stem + extras_by_year[year],
                code2, bl, extras_by_year[year],
                "擬似言語は、変数の役割・ループ回数・具体値のトレースの3点で押さえる。",
            ))
            n += 1
        theme = SEC_THEMES[yi]
        company = COS[yi]
        passage = sec_passage(company, year, theme)
        qs = SEC_Q[theme]
        for k, (pr, ch, ans, ex) in enumerate(qs, start=1):
            ch2, a2 = rot(list(ch), ans, k)
            out.append(multi(
                "fe", year, n, "セキュリティ",
                f"{company}の{['ランサムウェア対応','送金詐欺','内部不正','クラウド設定','供給連鎖'][yi]}（問{k}）",
                "長文を読み、空欄に最も適切な対策・判断を選べ。",
                "",
                [blank("a", "空欄", pr, ch2, a2, ex)],
                passage,
                "事例の弱点（認証、バックアップ、委託、権限、来歴）に直結する対策を選ぶ。一般論の最上級表現に釣られない。",
            ))
            n += 1
    return out


def enhance_essays(path: str) -> list[dict]:
    data = json.loads((OUT / path).read_text(encoding="utf-8"))
    for q in data:
        parts = []
        for p in q.get("parts", []):
            exp = p.get("explanation") or ""
            if len(exp) < 120:
                exp = (
                    f"{exp} 模範解答は「{p.get('answer','')}」。"
                    f"採点はルーブリック（{p.get('rubric','事例に即した具体性')}）に沿う。"
                    "本文の固有名詞・数値・制約を引用し、一般論だけで終わらせないこと。"
                    "選択問題は用語の定義とA社の弱点の対応を確認する。"
                )
            p = dict(p)
            p["explanation"] = exp
            parts.append(p)
        q["parts"] = parts
        # unique-ish title already includes company; append topic focus
        if "passage" in q and "【解答上の注意】" not in q["passage"]:
            q["passage"] = q["passage"] + (
                f"\n\n【解答上の注意】本問（{q.get('category','')}）では、"
                "空所補充・記号選択・記述を組み合わせて問う。"
                "記述は『誰が・何を・どの制約の下で・どう検証するか』を含める。"
            )
    return data


