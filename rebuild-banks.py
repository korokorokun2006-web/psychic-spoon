def dump(name: str, data: list) -> None:
    path = OUT / name
    path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {path.name:12} n={len(data):4} bytes={path.stat().st_size}")


def strip_wrap(stem: str) -> str:
    s = re.sub(r"^令和[^。]*。[^。]*の事例を念頭に、次の問いに答えよ。", "", stem)
    s = re.sub(r"（関連法規・規格は\d{4}年時点の一般的理解に基づく）", "", s)
    return s.strip()


def rot(choices: list[str], ans: int, k: int) -> tuple[list[str], int]:
    k = k % 4
    out = choices[k:] + choices[:k]
    return out, (ans - k) % 4


def expand_expl(choices: list[str], ans: int, exp: str) -> str:
    correct = choices[ans]
    others = [c for i, c in enumerate(choices) if i != ans]
    body = exp.strip()
    if not body.endswith("。"):
        body += "。"
    if len(body) < 80:
        body += f"正解は「{correct}」です。"
    tail = "誤りの選択肢は定義・目的・対象が異なります。"
    named = "、".join(f"「{o}」" for o in others)
    if named not in body and len(body) < 280:
        body += f" {named} は、それぞれ別の枠組みや用語であり本题の定義には当たりません。"
    elif tail not in body and "他の選択肢" not in body:
        body += " " + tail
    return body


def variant_pack(stem: str, choices: list[str], ans: int, exp: str, yi: int, company: str) -> tuple[str, list[str], int, str]:
    """Different question shapes from one original item; numeric answers get their own path."""
    ch = list(choices)
    correct = ch[ans]
    wrongs = [c for i, c in enumerate(ch) if i != ans]
    w1, w2, w3 = (wrongs + ["関連しない手法", "別概念", "対象外"])[:3]
    core = strip_wrap(stem)
    expl = expand_expl(ch, ans, exp)
    numeric = bool(re.match(r"^[\d.\-]+", correct)) or (len(correct) <= 4 and re.search(r"\d", correct))

    flavor = [
        "",
        "",
        "",
        "",
        "",
        "リスクを先に潰す観点で、",
        "次に取るべき実務として、",
        "監査人が証拠を求めるとき、",
        "限られた予算で優先するなら、",
        "定量的に検証するとき、",
    ]
    prefix = flavor[yi % len(flavor)]

    if numeric:
        shapes = [
            (core, ch, ans, expl),
            (f"次の条件で計算した値として適切なものはどれか。\n{core}", ch, ans, expl),
            (f"{company}の性能評価で次を求めた。{core}", *rot(ch, ans, 1), expl),
            (
                f"同じ設定で誤っている評価はどれか。正しい値は {correct} である。",
                [
                    f"正しい値は {w1} である。",
                    f"題意どおり計算すると {correct} になる。",
                    "単位と式の対応を確認する必要がある。",
                    "前提（ヒット率やビット幅など）を読み落とすと誤る。",
                ],
                0,
                expl,
            ),
            (
                f"この計算問題で求めた値 {correct} が意味するものとして適切なものはどれか。",
                [expl.split("。")[0] + "。", f"{w1} そのもの", f"{w2} の別名", "無次元の誤差率だけ"],
                0,
                expl,
            ),
        ]
        st, ch2, a2, ex2 = shapes[yi % 5]
        return prefix + st, ch2, a2, ex2

    kind = yi % 5
    if kind == 0:
        return prefix + core, ch, ans, expl
    if kind == 1:
        first = expl.split("。")[0]
        st = f"次の説明に最もよく当てはまる用語・手法はどれか。\n「{first}。」"
        ch2, a2 = rot(ch, ans, 1)
        return prefix + st, ch2, a2, expl
    if kind == 2:
        st = (
            f"{company}の会議で次の論点が挙がった。「{core.replace('はどれか。', '').replace('を何と呼ぶか。', '')}」。"
            "このとき用いるべき用語・枠組みとして適切なものはどれか。"
        )
        ch2, a2 = rot(ch, ans, 2)
        return prefix + st, ch2, a2, expl + f" 事例企業（{company}）でも定義は変わりません。"
    if kind == 3:
        st = f"「{correct}」に関する記述のうち、誤っているものはどれか。"
        ch3 = [
            f"{correct}は、{w1}と同じ意味である。",
            f"{correct}の定義として、現場で広く使われる説明に沿った内容である。",
            f"{correct}と{w2}は目的が異なり、混同すべきでない。",
            f"{correct}を選ぶ際は、他の類似手法との違いを確認する。",
        ]
        return prefix + st, ch3, 0, (
            f"「{correct}」と「{w1}」は別概念です。イ〜エは正しい注意点です。 元の定義: {expl}"
        )
    st = f"{correct}を用いる主な目的として、最も適切なものはどれか。"
    purposes = [
        expl.split("。")[0] + "こと。",
        f"{w1}を{w2}に置き換えること。",
        f"{w3}の計算式を暗記することだけを目的とすること。",
        "用語の英語略称を増やすこと。",
    ]
    return prefix + st, purposes, 0, expl + f" {correct}を使うのは、{expl.split('。')[0]}ためです。"


def uniquify_mcq(path: str, years: list[str], exam: str) -> list[dict]:
    raw = json.loads((OUT / path).read_text(encoding="utf-8"))
    by_year: dict[str, list] = {}
    for q in raw:
        by_year.setdefault(q["year"], []).append(q)
    base_year = years[0]
    base = by_year.get(base_year) or next(iter(by_year.values()))
    out: list[dict] = []
    for yi, year in enumerate(years):
        for j, q in enumerate(base):
            company = COS[(yi * 3 + j) % len(COS)]
            stem, ch, ans, exp = variant_pack(
                q["stem"], list(q["choices"]), int(q["answer"]), q["explanation"], yi, company
            )
            new = dict(q)
            new["year"] = year
            new["id"] = q["id"].replace(q["year"], year, 1)
            new["stem"] = stem
            new["choices"] = ch
            new["answer"] = ans
            new["explanation"] = exp
            out.append(new)
    return out


