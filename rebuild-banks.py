def blank(bid, label, prompt, choices, answer, explanation):
    return {
        "id": bid, "label": label, "prompt": prompt,
        "choices": choices, "answer": answer, "explanation": explanation,
    }


def multi(exam, year, n, cat, title, stem, code, blanks, passage="", explanation=""):
    return {
        "id": f"{exam}-{year}-b-{n:03d}",
        "kind": "multi",
        "exam": exam,
        "year": year,
        "field": "technology",
        "category": cat,
        "title": title,
        "passage": passage,
        "code": code,
        "stem": stem,
        "blanks": blanks,
        "explanation": explanation,
    }


