def expand_db_a() -> list[dict]:
    out = []
    for yi, year in enumerate(DB_SESS):
        n = 1
        for j, item in enumerate(DB_A1):
            stem, ch, ans, exp = item
            ch2, a = rot(list(ch), ans, yi + j)
            out.append(mcq("db", year, "a1", n, "advanced", "午前I", wrap(year, co(yi + j), stem), ch2, a, exp))
            n += 1
        n = 1
        for j, item in enumerate(DB_A2):
            stem, ch, ans, exp = item
            ch2, a = rot(list(ch), ans, yi + j)
            out.append(mcq("db", year, "a2", n, "advanced", "午前II", wrap(year, co(yi + j, 3), stem), ch2, a, exp))
            n += 1
    return out


