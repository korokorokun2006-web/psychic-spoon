def rot(choices: list[str], ans: int, k: int) -> tuple[list[str], int]:
    k = k % 4
    out = choices[k:] + choices[:k]
    return out, (ans - k) % 4


def mcq(exam: str, year: str, phase: str, n: int, field: str, cat: str,
        stem: str, choices: list[str], ans: int, exp: str, **kw) -> dict:
    return {
        "id": f"{exam}-{year}-{phase}-{n:03d}",
        "kind": "mcq",
        "exam": exam,
        "year": year,
        "field": field,
        "category": cat,
        "stem": stem,
        "choices": list(choices),
        "answer": ans,
        "explanation": exp,
        **kw,
    }


